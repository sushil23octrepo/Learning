# To form a string with triple quotes, you may use triple single quotes, 
# or triple double quotes − both versions are similar.

var = '''Welcome to TutorialsPoint'''
print ("var:", var)

var = """Welcome to TutorialsPoint"""
print ("var:", var)

# Triple quoted string is useful to form a multi-line string.
var = '''
Welcome To
Python Tutorial
from TutorialsPoint
'''
print ("var:", var)

# Output of multiple line string:
# var:
# Welcome To
# Python Tutorial
# from TutorialsPoint

